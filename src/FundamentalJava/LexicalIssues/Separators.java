package FundamentalJava.LexicalIssues;

public class Separators {

    /**
     * Separators (Pemisah)
     * Separators adalah karakter khusus yang digunakan untuk memisahkan dan mengorganisir elemen-elemen dalam kode.
     */

    /**
     * Macam-macam Separator
     * () Tanda kurung
     * -Mengapit daftar parameter dalam definisi methode
     * -Mendefinisikan prioritas dalam ekspresi
     * -Mengapit tipe data saat casting
     */

    /**
     * {} Kurung kurawal
     * -Mendefinisikan blok kode (untuk class, methode, dan scope lokal)
     * -Menginisialisasi array
     */

    /**
     * [] Kurung siku
     * -Mendeklarasikan tipe array
     * -Mengakses nilai elemen array
     */

    /**
     * ; Titik koma
     * -Mengakhiri sebuah pernyataan (statement)
     */

    /**
     * , Koma
     * -Memisahkan beberapa identifier dalam satu deklarasi atau menghubungkan pernyataan
     *  dalam perulangan for
     */

    /**
     * . Titik
     * -Memisahkan nama paket dari subpaket atau class, atau memisahkan variabel/methode
     *  dari objek yang merujuknya
     */

    /**
     * :: Titik dua ganda
     * -Digunakan untuk membuat referensi metode atau konstruktor
     */

}
