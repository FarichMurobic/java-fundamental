package FundamentalJava.LexicalIssues;

public class Identifiers {

    /**
     * Identifiers (Pengenal)
     * Identifiers digunakan untuk memberi nama pada hal-hal dalam program, seperti kelas, variabel, dan metode.
     *
     * Aturan Penamaan:
     * - Bisa berupa kombinasi huruf besar dan kecil, angka, atau karakter _ (underscore) dan $ (dollar sign).
     * - Tidak boleh dimulai dengan angka.
     * - Java case-sensitive, jadi nilai berbeda dengan Nilai.
     *
     * Contoh Valid: rataRataSuhu, jumlah, a4, $tes.
     * Contoh Tidak Valid: 2jumlah (dimulai dengan angka), suhu-tinggi (mengandung karakter -).
     */

}
